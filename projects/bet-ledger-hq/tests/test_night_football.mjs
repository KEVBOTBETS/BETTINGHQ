import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),C=require('../night-football-core.js');
const now=Date.parse('2026-10-08T19:00Z'),meta={generated_at:'2026-10-08T18:30Z'};
const g=(id,date,other={})=>({game_id:id,date,home:'DAL',away:'TB',...other});
const games=[g('thu','2026-10-09T00:15Z'),g('thu-day','2026-10-08T17:00Z'),g('sun','2026-10-12T00:20Z'),g('sun-day','2026-10-11T20:25Z'),g('mon1','2026-10-12T23:00Z'),g('mon2','2026-10-13T00:15Z'),g('cancel','2026-10-09T00:15Z',{canceled:true})];
assert.deepEqual(C.schedule(games,'thursday',now).flatMap(d=>d.games.map(g=>g.game_id)),['thu']);
assert.deepEqual(C.schedule(games,'sunday',now).flatMap(d=>d.games.map(g=>g.game_id)),['sun']);
assert.deepEqual(C.schedule(games,'monday',now)[0].games.map(g=>g.game_id),['mon1','mon2']);
assert.equal(C.defaultDate(C.schedule(games,'thursday',now),now),'2026-10-08');
assert.equal(C.defaultDate(C.schedule(games,'thursday',now),Date.parse('2026-10-09T05:00Z')),'2026-10-08');
assert.equal(C.schedule([g('winter','2026-11-06T01:15Z')],'thursday',Date.parse('2026-11-05T19:00Z'))[0].day,'2026-11-05');
const q={game_id:'thu',game_date:'2026-10-09T00:15Z',price:-110,book:'Book',odds_observed_at:'2026-10-08T18:00Z',tier:'GOOD'};
assert(C.qualified(q,meta,now));
for(const change of [{held:true},{odds_verified:false},{tier:'PASS'},{filtered:'data error'},{price_source:'model'},{price:null},{odds_observed_at:'2026-10-08T12:00Z'},{odds_observed_at:'2026-10-08T20:00Z'}])assert.equal(C.qualified({...q,...change},meta,now),false);
assert.equal(C.qualified(q,meta,Date.parse(q.game_date)),false);
assert.equal(C.qualified(q,meta,now,true),false);
assert.equal(C.qualified(q,{generated_at:'2026-10-08T10:00Z'},now),false);
assert.deepEqual(C.rowsFor([{event_id:'thu'},{event_id:'sun'}],[games[0]]),[{event_id:'thu'}]);
const tickets=[{id:'same',legs:[{event_id:'thu'},{event_id:'thu'}]},{id:'mixed',legs:[{event_id:'thu'},{event_id:'sun'}]},{id:'one',legs:[{event_id:'thu'}]}];
assert.deepEqual(C.ticketsFor(tickets,[games[0]]).map(t=>t.id),['same']);
console.log('Night football: Toronto dates, DST, evening-only schedules, Monday doubleheader, retained current night, quote gates and exact parlay event scope passed');
